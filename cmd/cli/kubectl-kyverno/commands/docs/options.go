package docs

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

type options struct {
	path       string
	website    bool
	autogenTag bool
	noDate     bool
	mdLinks    bool
}

func (o options) validate(root *cobra.Command) error {
	if o.path == "" {
		return errors.New("path is required")
	}
	if root == nil {
		return errors.New("root command is required")
	}
	return nil
}

func (o options) execute(root *cobra.Command) error {
	prepender := empty
	linkHandler := identity
	if o.website {
		prepender = websitePrepender(o.noDate)
		if !o.mdLinks {
			linkHandler = websiteLinkHandler
		}
	}
	if _, err := os.Stat(o.path); errors.Is(err, os.ErrNotExist) {
		if err := os.MkdirAll(o.path, os.ModeDir|os.ModePerm); err != nil {
			return err
		}
	}
	root.DisableAutoGenTag = !o.autogenTag

	if err := doc.GenMarkdownTreeCustom(root, o.path, prepender, linkHandler); err != nil {
		return err
	}

	return postProcessDocs(o.path)
}

// postProcessDocs sanitizes the markdown files generated by Cobra.
// It strips raw code block formatting and converts flags into a bulleted list with explicit HTML anchors.
func postProcessDocs(dir string) error {
	// Cobra always separates the flag string from the description with 2 or more spaces
	splitRegex := regexp.MustCompile(`\s{2,}`)
	longFlagRegex := regexp.MustCompile(`--([a-zA-Z0-9_-]+)`)
	shortFlagRegex := regexp.MustCompile(`-([a-zA-Z0-9_-]+)`)

	return filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || filepath.Ext(path) != ".md" {
			return nil
		}

		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}

		fileStr := string(content)
		if !strings.Contains(fileStr, "### Options") {
			return nil
		}

		lines := strings.Split(fileStr, "\n")
		var out []string
		inOptions := false

		for _, line := range lines {
			if strings.HasPrefix(line, "### Options") {
				inOptions = true
				out = append(out, line)
				continue
			}

			if inOptions && strings.HasPrefix(line, "### ") {
				inOptions = false
				out = append(out, line)
				continue
			}

			if inOptions {
				if strings.HasPrefix(strings.TrimSpace(line), "```") {
					continue
				}

				trimmed := strings.TrimSpace(line)
				if strings.HasPrefix(trimmed, "-") {
					parts := splitRegex.Split(trimmed, 2)
					flags := parts[0]
					desc := ""
					if len(parts) > 1 {
						desc = parts[1]
					}

					anchor := ""
					if match := longFlagRegex.FindStringSubmatch(flags); match != nil {
						anchor = strings.ToLower(match[1])
					} else if match := shortFlagRegex.FindStringSubmatch(flags); match != nil {
						anchor = strings.ToLower(match[1])
					}

					out = append(out, fmt.Sprintf("* **<a id=\"%s\"></a>%s**: %s", anchor, flags, desc))
				} else if trimmed != "" {
					out = append(out, line)
				}
			} else {
				out = append(out, line)
			}
		}

		return os.WriteFile(path, []byte(strings.Join(out, "\n")), info.Mode())
	})
}
