package docs

import (
	"errors"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"[github.com/spf13/cobra/doc](https://github.com/spf13/cobra/doc)"
	"[github.com/spf13/cobra](https://github.com/spf13/cobra)"
)

type options struct {
	path       string
	website    bool
	autogenTag bool
	noDate     bool
	mdLinks    bool
}

func (o options) validate(root *cobra.Command) error {
	if o.path == "" {
		return errors.New("path is required")
	}
	if root == nil {
		return errors.New("root command is required")
	}
	return nil
}

func (o options) execute(root *cobra.Command) error {
	prepender := empty
	linkHandler := identity
	if o.website {
		prepender = websitePrepender(o.noDate)
		if !o.mdLinks {
			linkHandler = websiteLinkHandler
		}
	}
	if _, err := os.Stat(o.path); errors.Is(err, os.ErrNotExist) {
		if err := os.MkdirAll(o.path, os.ModeDir|os.ModePerm); err != nil {
			return err
		}
	}
	root.DisableAutoGenTag = !o.autogenTag

	if err := doc.GenMarkdownTreeCustom(root, o.path, prepender, linkHandler); err != nil {
		return err
	}

	return postProcessDocs(o.path, root.Name())
}

// postProcessDocs sanitizes the markdown files generated by Cobra.
// It strips raw code block formatting and converts flags into a bulleted list with explicit HTML anchors.
func postProcessDocs(dir string, cmdName string) error {
	longFlagRegex := regexp.MustCompile(`--([a-zA-Z0-9_-]+)`)
	shortFlagRegex := regexp.MustCompile(`(?:^|\s)-([a-zA-Z0-9])\b`)
	spacesRegex := regexp.MustCompile(`\s{2,}`)

	return filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		baseName := filepath.Base(path)
		if info.IsDir() || filepath.Ext(baseName) != ".md" || !strings.HasPrefix(baseName, cmdName) {
			return nil
		}

		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}

		lines := strings.Split(string(content), "\n")
		var newLines []string
		inOptions := false
		fencesRemoved := 0

		for _, line := range lines {
			trimmedLine := strings.TrimSpace(line)

			if trimmedLine == "### Options" {
				inOptions = true
				fencesRemoved = 0
				newLines = append(newLines, line)
				continue
			}

			if inOptions {
				if strings.HasPrefix(trimmedLine, "### ") {
					inOptions = false
					// Inject a blank line before the next heading if it is missing
					if len(newLines) > 0 && strings.TrimSpace(newLines[len(newLines)-1]) != "" {
						newLines = append(newLines, "")
					}
					newLines = append(newLines, line)
					continue
				}

				// Only strip the first pair of fences that wrap the flags list
				if (trimmedLine == "```" || trimmedLine == "~~~") && fencesRemoved < 2 {
					fencesRemoved++
					continue
				}

				if trimmedLine == "" {
					newLines = append(newLines, line)
					continue
				}

				parts := spacesRegex.Split(trimmedLine, 2)
				flagPart := strings.TrimSpace(parts[0])
				descPart := ""

				if len(parts) > 1 {
					descPart = strings.TrimSpace(parts[1])
				}

				anchor := ""
				longMatch := longFlagRegex.FindStringSubmatch(flagPart)

				if len(longMatch) > 1 {
					anchor = strings.ToLower(longMatch[1])
				} else {
					shortMatch := shortFlagRegex.FindStringSubmatch(flagPart)
					if len(shortMatch) > 1 {
						anchor = strings.ToLower(shortMatch[1])
					}
				}

				if anchor != "" {
					escapedFlag := html.EscapeString(flagPart)
					escapedFlag = strings.ReplaceAll(escapedFlag, "*", `\*`)
					escapedFlag = strings.ReplaceAll(escapedFlag, "_", `\_`)

					newLine := fmt.Sprintf("* **<a id=\"%s\"></a>%s**: %s", anchor, escapedFlag, descPart)
					newLines = append(newLines, newLine)
				} else {
					newLines = append(newLines, line)
				}
			} else {
				newLines = append(newLines, line)
			}
		}

		return os.WriteFile(path, []byte(strings.Join(newLines, "\n")), info.Mode())
	})
}
