#!/usr/bin/env bash
#
# verify-policies-psa-version.sh
#
# Asserts the kyverno-policies chart renders the Pod Security Admission (PSA)
# behavior for each podSecurityVersion: the sysctl and SELinux allow-lists,
# the host probes policy, the user namespace relaxation, the
# kyverno.io/pod-security-version annotation, and the errors for invalid values.
#
# verify-policies-sysctls.sh covers podSecurityVersion=latest for sysctls.
#
# It also checks that the CLI test policies in test/cli/test-validating-policy/pss-psa-version
# match the chart. Those tests run the rendered policies against Pods with
# `kyverno test`. A v1.x directory pins podSecurityVersion, and a latest-k8s-v1.x
# directory uses latest on that Kubernetes version. There is one directory for each
# distinct behavior, and the script checks that every other version renders the same
# policies as one of them. Run with --update to regenerate them after a chart change.
# Every directory renders with podSecurityUserNamespaces=true.
#
# This needs no cluster: `helm template` renders locally.
#
# Usage: scripts/verify-policies-psa-version.sh [--update]

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHART_DIR="${ROOT_DIR}/charts/kyverno-policies"
CLI_TEST_DIR="${ROOT_DIR}/test/cli/test-validating-policy/pss-psa-version"
HELM="${HELM:-helm}"
UPDATE="${1:-}"

log() { echo "[verify-policies-psa-version] $*"; }
fail() { echo "[verify-policies-psa-version] FAIL: $*" >&2; exit 1; }

# normalize strips carriage returns, trailing whitespace, and blank lines, which differ
# between Helm versions and platforms, so the fixtures don't depend on them.
normalize() { tr -d '\r' | sed -e 's/[[:space:]]*$//' -e '/^$/d'; }

# cli_test_policy prints the policies a CLI test directory expects for a podSecurityVersion and Kubernetes version, plus extra helm args.
cli_test_policy() {
  local version="$1" kube="$2"
  shift 2
  echo "# Generated by scripts/verify-policies-psa-version.sh --update. Do not edit."
  "${HELM}" template kyverno-policies "${CHART_DIR}" \
    --kube-version "${kube}" \
    --set podSecurityVersion="${version}" \
    --set podSecurityStandard=custom \
    --set 'podSecurityPolicies={restrict-sysctls,disallow-selinux,disallow-host-probes,disallow-proc-mount,require-run-as-nonroot,require-run-as-non-root-user}' \
    --set podSecurityUserNamespaces=true \
    "$@" |
    normalize
}

log "CLI test policies in ${CLI_TEST_DIR}"
for dir in "${CLI_TEST_DIR}"/*/; do
  name="$(basename "${dir}")"
  case "${name}" in
    latest-k8s-v1.*) version=latest kube="${name#latest-k8s-}.0" ;;
    v1.*) version="${name}" kube=v1.37.0 ;;
    *) fail "unknown CLI test directory ${dir}, want v1.x or latest-k8s-v1.x" ;;
  esac
  if [ "${UPDATE}" = "--update" ]; then
    cli_test_policy "${version}" "${kube}" >"${dir}policy.yaml"
    log "  UPDATED ${name}"
  elif ! diff -q <(cli_test_policy "${version}" "${kube}") "${dir}policy.yaml" >/dev/null; then
    fail "${dir}policy.yaml is out of date, run scripts/verify-policies-psa-version.sh --update"
  else
    log "  OK   ${name} policy.yaml matches the chart"
  fi
done

# same_policies checks that a case without a CLI test directory renders the same
# policies as a tested one, apart from the annotation, so the CLI test covers it.
# Usage: same_policies VERSION KUBE TESTED_VERSION TESTED_KUBE [helm args]
same_policies() {
  local version="$1" kube="$2" tested="$3" tested_kube="$4"
  shift 4
  local dir="${tested}"
  [ "${tested}" = latest ] && dir="latest-k8s-${tested_kube%.0}"
  [ -d "${CLI_TEST_DIR}/${dir}" ] || fail "no CLI test directory ${dir}"
  diff -q <(cli_test_policy "${version}" "${kube}" "$@" | grep -v 'kyverno.io/pod-security-version:') \
    <(cli_test_policy "${tested}" "${tested_kube}" "$@" | grep -v 'kyverno.io/pod-security-version:') >/dev/null ||
    fail "${version} on Kubernetes ${kube}${*:+ ($*)} does not match the ${dir} CLI test"
  log "  OK   ${version} on Kubernetes ${kube}${*:+ ($*)} matches the ${dir} CLI test"
}

log "cases without a CLI test directory enforce the same as a tested case"
same_policies v1.26 v1.37.0 v1.25 v1.37.0
same_policies v1.28 v1.37.0 v1.27 v1.37.0
same_policies v1.30 v1.37.0 v1.29 v1.37.0
same_policies v1.33 v1.37.0 v1.32 v1.37.0
same_policies v1.36 v1.37.0 v1.35 v1.37.0
same_policies v1.37 v1.37.0 v1.40 v1.37.0
# latest on 1.33 follows the version gates for sysctls but keeps the legacy behavior for the rest.
same_policies latest v1.33.0 v1.32 v1.37.0 --show-only templates/baseline/restrict-sysctls.cel.yaml
for template in baseline/disallow-selinux baseline/disallow-proc-mount restricted/require-run-as-nonroot restricted/require-run-as-non-root-user; do
  same_policies latest v1.33.0 latest v1.25.0 --show-only "templates/${template}.cel.yaml"
done

# render prints the chart for a Kubernetes version and podSecurityVersion, plus extra helm args.
render() {
  local kube="$1" version="$2"
  shift 2
  "${HELM}" template verify "${CHART_DIR}" \
    --kube-version "${kube}" \
    --set podSecurityVersion="${version}" \
    "$@" |
    normalize
}

# expect checks that a count from the rendered chart equals the wanted value.
expect() {
  local what="$1" want="$2" got="$3"
  [ "${got}" = "${want}" ] || fail "${what}: want ${want}, got ${got}"
  log "  OK   ${what}: ${got}"
}

count_sysctls() {
  render "$1" "$2" --show-only templates/baseline/restrict-sysctls.cel.yaml |
    grep 'sysctls.all(' | grep -o "'[a-z0-9_.]*'" | wc -l | tr -d ' '
}

count_engine_t() {
  render "$1" "$2" --show-only templates/baseline/disallow-selinux.cel.yaml |
    grep -c container_engine_t || true
}

count_policy() {
  local kube="$1" version="$2" name="$3"
  shift 3
  render "${kube}" "${version}" "$@" | grep -c "^  name: ${name}\$" || true
}

count_relax() {
  render "$1" "$2" "${@:3}" | grep -c 'hostUsers.orValue(true) == false' || true
}

# count_exempt_messages counts denial messages that say hostUsers: false Pods are exempt.
count_exempt_messages() {
  render "$1" "$2" "${@:3}" | grep -c 'spec.hostUsers to `false`' || true
}

annotations() {
  render "$1" "$2" | grep 'kyverno.io/pod-security-version:' | sort -u | sed 's/^ *//'
}

log "supported range"
helper_range() {
  grep -o "define \"kyverno-policies.psa$1Version\" -}}[0-9.]*" "${CHART_DIR}/templates/_helpers.tpl" | grep -o '[0-9.]*$'
}
want_range="v$(helper_range Min)-v$(helper_range Max)"
got_range="$(grep 'kyverno.io/pod-security-versions:' "${CHART_DIR}/Chart.yaml" | awk '{print $2}')"
expect "Chart.yaml kyverno.io/pod-security-versions matches psaMinVersion and psaMaxVersion" "${want_range}" "${got_range}"
min="v$(helper_range Min)"
max="v$(helper_range Max)"
expect "Chart.yaml kubeVersion matches psaMinVersion" ">=${min#v}.0-0" "$(grep '^kubeVersion:' "${CHART_DIR}/Chart.yaml" | tr -d '"\r' | awk '{print $2}')"
# has_text checks that a chart file states the supported range.
has_text() {
  grep -qF -- "$2" "${CHART_DIR}/$1" || fail "$1 does not contain: $2"
  log "  OK   $1 contains: $2"
}
has_text Chart.yaml "from ${min} to ${max}"
for file in values.yaml README.md.gotmpl README.md; do
  has_text "${file}" "from \`${min}\` to \`${max}\`"
  has_text "${file}" "newer than \`${max}\` uses \`${max}\`"
done

log "sysctls (PSA adds names in v1.27, v1.29, v1.32, and v1.37)"
expect "v1.25 sysctls" 5 "$(count_sysctls v1.37.0 v1.25)"
expect "v1.26 sysctls" 5 "$(count_sysctls v1.37.0 v1.26)"
expect "v1.27 sysctls" 6 "$(count_sysctls v1.37.0 v1.27)"
expect "v1.28 sysctls" 6 "$(count_sysctls v1.37.0 v1.28)"
expect "v1.29 sysctls" 10 "$(count_sysctls v1.37.0 v1.29)"
expect "v1.31 sysctls" 10 "$(count_sysctls v1.37.0 v1.31)"
expect "v1.32 sysctls" 12 "$(count_sysctls v1.25.0 v1.32)"
expect "v1.36 sysctls" 12 "$(count_sysctls v1.25.0 v1.36)"
expect "v1.37 sysctls" 14 "$(count_sysctls v1.25.0 v1.37)"
expect "v1.40 sysctls (uses v1.37)" 14 "$(count_sysctls v1.25.0 v1.40)"
expect "latest on Kubernetes 1.25 sysctls (keeps the v1.29 list)" 10 "$(count_sysctls v1.25.0 latest)"
expect "latest on Kubernetes 1.31 sysctls" 10 "$(count_sysctls v1.31.0 latest)"
expect "latest on Kubernetes 1.32 sysctls" 12 "$(count_sysctls v1.32.0 latest)"
expect "latest on Kubernetes 1.36 sysctls" 12 "$(count_sysctls v1.36.0 latest)"
expect "latest on Kubernetes 1.37 sysctls" 14 "$(count_sysctls v1.37.0 latest)"

log "SELinux (PSA allows container_engine_t from v1.31)"
expect "v1.30 container_engine_t" 0 "$(count_engine_t v1.37.0 v1.30)"
expect "v1.31 container_engine_t" 4 "$(count_engine_t v1.25.0 v1.31)"
expect "latest on Kubernetes 1.25 container_engine_t" 4 "$(count_engine_t v1.25.0 latest)"

log "host probes (PSA adds the check in v1.34)"
expect "v1.33 disallow-host-probes" 0 "$(count_policy v1.37.0 v1.33 disallow-host-probes)"
expect "v1.34 disallow-host-probes" 1 "$(count_policy v1.30.0 v1.34 disallow-host-probes)"
expect "latest on Kubernetes 1.33 disallow-host-probes" 0 "$(count_policy v1.33.0 latest disallow-host-probes)"
expect "latest on Kubernetes 1.34 disallow-host-probes" 1 "$(count_policy v1.34.0 latest disallow-host-probes)"

log "user namespaces (PSA relaxes procMount, runAsNonRoot, and runAsUser from v1.35)"
USERNS=(--set podSecurityUserNamespaces=true)
RESTRICTED=(--set podSecurityStandard=restricted)
expect "baseline v1.34 relaxations" 0 "$(count_relax v1.37.0 v1.34 "${USERNS[@]}")"
expect "baseline v1.35 relaxations" 1 "$(count_relax v1.30.0 v1.35 "${USERNS[@]}")"
expect "restricted v1.34 relaxations" 0 "$(count_relax v1.37.0 v1.34 "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "restricted v1.35 relaxations" 2 "$(count_relax v1.30.0 v1.35 "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "restricted v1.34 disallow-proc-mount-strict" 0 "$(count_policy v1.37.0 v1.34 disallow-proc-mount-strict "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "restricted v1.35 disallow-proc-mount-strict" 1 "$(count_policy v1.30.0 v1.35 disallow-proc-mount-strict "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "latest on Kubernetes 1.30 relaxations" 2 "$(count_relax v1.30.0 latest "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "v1.35 without podSecurityUserNamespaces relaxations" 0 "$(count_relax v1.37.0 v1.35 "${RESTRICTED[@]}")"
# Denial messages mention the exemption only where the relaxation applies.
expect "baseline v1.34 exemption messages" 0 "$(count_exempt_messages v1.37.0 v1.34 "${USERNS[@]}")"
expect "baseline v1.35 exemption messages" 1 "$(count_exempt_messages v1.30.0 v1.35 "${USERNS[@]}")"
expect "restricted v1.34 exemption messages" 0 "$(count_exempt_messages v1.37.0 v1.34 "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "restricted v1.35 exemption messages" 2 "$(count_exempt_messages v1.30.0 v1.35 "${USERNS[@]}" "${RESTRICTED[@]}")"
expect "latest on Kubernetes 1.30 exemption messages" 2 "$(count_exempt_messages v1.30.0 latest "${USERNS[@]}" "${RESTRICTED[@]}")"

log "kyverno.io/pod-security-version annotation"
expect "v1.34 annotation" 'kyverno.io/pod-security-version: "v1.34"' "$(annotations v1.37.0 v1.34)"
expect "latest on Kubernetes 1.36 annotation" 'kyverno.io/pod-security-version: "latest (v1.36)"' "$(annotations v1.36.0 latest)"
expect "latest on Kubernetes 1.40 annotation" 'kyverno.io/pod-security-version: "latest (v1.37)"' "$(annotations v1.40.0 latest)"

log "invalid values fail the render"
for version in foo 1.34 v2.0 v1.034 v1.24; do
  if render v1.37.0 "${version}" >/dev/null 2>&1; then
    fail "podSecurityVersion=${version} rendered, want an error"
  fi
  log "  OK   podSecurityVersion=${version} fails"
done
if render v1.37.0 v1.24 --set podSecurityStandard=privileged >/dev/null 2>&1; then
  fail "podSecurityVersion=v1.24 rendered with the privileged profile, want an error"
fi
log "  OK   podSecurityVersion=v1.24 fails with the privileged profile"

log "kyverno-policies renders the PSA behavior for every podSecurityVersion"
