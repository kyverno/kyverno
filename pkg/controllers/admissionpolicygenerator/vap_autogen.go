// autogenSourceLabel is applied to every VAP/VAPBinding created by handleAutogenVAPs
// so that pruneStaleAutogenVAPs can list them without relying on hard-coded config keys.
const autogenSourceLabel = "policies.kyverno.io/autogen-source"

// maxAutogenVAPNameLength keeps room for the "-binding" suffix added to the VAP binding name
// within the 253 character limit of a Kubernetes object name.
const maxAutogenVAPNameLength = 253 - len("-binding")

// autogenVAPName returns the name for an autogenerated VAP derived from a ValidatingPolicy.
// The config key is sanitized to a valid DNS subdomain segment, and names that would exceed
// the length limit are truncated and suffixed with a stable hash of the full name.
func autogenVAPName(polName, configKey string) string {
	name := "vpol-" + polName + "-autogen-" + sanitizeNameSegment(configKey)
	if len(name) <= maxAutogenVAPNameLength {
		return name
	}
	sum := sha256.Sum256([]byte(name))
	hash := hex.EncodeToString(sum[:])[:10]
	prefix := strings.TrimRight(name[:maxAutogenVAPNameLength-len(hash)-1], "-.")
	return prefix + "-" + hash
}

// sanitizeNameSegment lowercases s and replaces any character that is not valid in a
// DNS subdomain name with '-'.
func sanitizeNameSegment(s string) string {
	s = strings.ToLower(s)
	return strings.Trim(strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' || r == '.' {
			return r
		}
		return '-'
	}, s), "-.")
}

// handleAutogenVAPs creates or updates ValidatingAdmissionPolicies for each autogenerated
// pod-controller variant of the given ValidatingPolicy. It is only reached when
// Spec.GenerateValidatingAdmissionPolicyEnabled() is true (that is,
// spec.autogen.validatingAdmissionPolicy.enabled=true) so that pod-controller kinds are
// governed by native VAPs rather than Kyverno admission webhooks.
func (c *controller) handleAutogenVAPs(ctx context.Context, pol *policiesv1beta1.ValidatingPolicy, exceptions []engineapi.GenericException) error {
	autogenConfigs, err := vpolautogen.Autogen(pol)
	if err != nil {
		return fmt.Errorf("failed to generate autogen configs for policy %s: %w", pol.GetName(), err)
	}

	// Track which autogen VAP names are still active so we can remove stale ones.
	activeNames := make(map[string]struct{}, len(autogenConfigs))

	for _, configKey := range slices.Sorted(maps.Keys(autogenConfigs)) {
		autogenConfig := autogenConfigs[configKey]
		vapName := autogenVAPName(pol.GetName(), configKey)
		activeNames[vapName] = struct{}{}

		if err := c.reconcileAutogenVAP(ctx, pol, vapName, configKey, autogenConfig, exceptions); err != nil {
			return err
		}
	}

	// Delete autogen VAPs whose config keys are no longer present (e.g., because the
	// autogen controller list changed).
	return c.pruneStaleAutogenVAPs(ctx, pol, activeNames)
}

// reconcileAutogenVAP creates or updates a single autogenerated VAP.
func (c *controller) reconcileAutogenVAP(
	ctx context.Context,
	pol *policiesv1beta1.ValidatingPolicy,
	vapName string,
	configKey string,
	autogenConfig policiesv1beta1.ValidatingPolicyAutogen,
	exceptions []engineapi.GenericException,
) error {
	// Build a temporary ValidatingPolicy whose Spec is the autogenerated spec.
	// The parent policy's identity fields (name, UID) are used for owner references and
	// its labels are kept so that label driven behaviour (e.g. reporting exclusion) carries over.
	autogenPol := &policiesv1beta1.ValidatingPolicy{
		TypeMeta:   pol.TypeMeta,
		ObjectMeta: metav1.ObjectMeta{Name: pol.GetName(), UID: pol.GetUID(), Labels: pol.GetLabels()},
		Spec:       *autogenConfig.Spec,
	}
	// Preserve validation actions from the parent policy.
	autogenPol.Spec.ValidationAction = pol.Spec.ValidationAction

	autogenWrapper := engineapi.NewValidatingPolicy(autogenPol)

	var rewrittenExceptions []engineapi.GenericException
	for _, e := range exceptions {
		celEx := e.AsCELException()
		if celEx != nil {
			clonedEx := celEx.DeepCopy()
			for i, cond := range clonedEx.Spec.MatchConditions {
				clonedEx.Spec.MatchConditions[i].Expression = string(celautogen.Apply(
					[]byte(cond.Expression),
					celautogen.ReplacementsMap[celautogen.ConfigsMap[configKey].ReplacementsRef]...,
				))
			}
			rewrittenExceptions = append(rewrittenExceptions, engineapi.NewCELPolicyException(clonedEx))
		} else {
			rewrittenExceptions = append(rewrittenExceptions, e)
		}
	}

	vapBindingName := constructBindingName(vapName)

	observedVAP, vapErr := c.getValidatingAdmissionPolicy(vapName)
	observedVAPbinding, vapBindingErr := c.getValidatingAdmissionPolicyBinding(vapBindingName)

	if vapErr != nil {
		if !apierrors.IsNotFound(vapErr) {
			return fmt.Errorf("failed to get validatingadmissionpolicy %s: %w", vapName, vapErr)
		}
		observedVAP = &admissionregistrationv1.ValidatingAdmissionPolicy{
			ObjectMeta: metav1.ObjectMeta{Name: vapName},
		}
	}
	if vapBindingErr != nil {
		if !apierrors.IsNotFound(vapBindingErr) {
			return fmt.Errorf("failed to get validatingadmissionpolicybinding %s: %w", vapBindingName, vapBindingErr)
		}
		observedVAPbinding = &admissionregistrationv1.ValidatingAdmissionPolicyBinding{
			ObjectMeta: metav1.ObjectMeta{Name: vapBindingName},
		}
	}

	if observedVAP.ResourceVersion == "" {
		if observedVAP.Labels == nil {
			observedVAP.Labels = make(map[string]string)
		}
		observedVAP.Labels[autogenSourceLabel] = pol.GetName()
		if err := admissionpolicy.BuildValidatingAdmissionPolicy(c.discoveryClient, observedVAP, autogenWrapper, rewrittenExceptions); err != nil {
			return fmt.Errorf("failed to build autogen validatingadmissionpolicy %s: %w", vapName, err)
		}
		if _, err := c.client.AdmissionregistrationV1().ValidatingAdmissionPolicies().Create(ctx, observedVAP, metav1.CreateOptions{}); err != nil {
			return fmt.Errorf("failed to create autogen validatingadmissionpolicy %s: %w", vapName, err)
		}
	} else {
		if _, err := controllerutils.Update(ctx, observedVAP, c.client.AdmissionregistrationV1().ValidatingAdmissionPolicies(), func(observed *admissionregistrationv1.ValidatingAdmissionPolicy) error {
			if observed.Labels == nil {
				observed.Labels = make(map[string]string)
			}
			observed.Labels[autogenSourceLabel] = pol.GetName()
			return admissionpolicy.BuildValidatingAdmissionPolicy(c.discoveryClient, observed, autogenWrapper, rewrittenExceptions)
		}); err != nil {
			return fmt.Errorf("failed to update autogen validatingadmissionpolicy %s: %w", vapName, err)
		}
	}

	if observedVAPbinding.ResourceVersion == "" {
		if observedVAPbinding.Labels == nil {
			observedVAPbinding.Labels = make(map[string]string)
		}
		observedVAPbinding.Labels[autogenSourceLabel] = pol.GetName()
		if err := admissionpolicy.BuildValidatingAdmissionPolicyBinding(observedVAPbinding, autogenWrapper); err != nil {
			return fmt.Errorf("failed to build autogen validatingadmissionpolicybinding %s: %w", vapBindingName, err)
		}
		// Override the PolicyName to point to the autogen VAP (not "vpol-{name}").
		observedVAPbinding.Spec.PolicyName = vapName
		if _, err := c.client.AdmissionregistrationV1().ValidatingAdmissionPolicyBindings().Create(ctx, observedVAPbinding, metav1.CreateOptions{}); err != nil {
			return fmt.Errorf("failed to create autogen validatingadmissionpolicybinding %s: %w", vapBindingName, err)
		}
	} else {
		if _, err := controllerutils.Update(ctx, observedVAPbinding, c.client.AdmissionregistrationV1().ValidatingAdmissionPolicyBindings(), func(observed *admissionregistrationv1.ValidatingAdmissionPolicyBinding) error {
			if observed.Labels == nil {
				observed.Labels = make(map[string]string)
			}
			observed.Labels[autogenSourceLabel] = pol.GetName()
			if err := admissionpolicy.BuildValidatingAdmissionPolicyBinding(observed, autogenWrapper); err != nil {
				return err
			}
			observed.Spec.PolicyName = vapName
			return nil
		}); err != nil {
			return fmt.Errorf("failed to update autogen validatingadmissionpolicybinding %s: %w", vapBindingName, err)
		}
	}

	return nil
}

// deleteAutogenVAPs removes all autogenerated VAPs for the given policy.
// Called when spec.autogen.validatingAdmissionPolicy.enabled is set to false or removed.
func (c *controller) deleteAutogenVAPs(ctx context.Context, pol *policiesv1beta1.ValidatingPolicy) error {
	return c.pruneStaleAutogenVAPs(ctx, pol, nil)
}

// pruneStaleAutogenVAPs deletes autogen VAPs (and their bindings) that are not in activeNames.
// Passing nil for activeNames deletes all autogen VAPs owned by the policy.
// Discovery is label-based so pruning stays correct if the autogen config key set ever expands.
func (c *controller) pruneStaleAutogenVAPs(ctx context.Context, pol *policiesv1beta1.ValidatingPolicy, activeNames map[string]struct{}) error {
	selector := labels.SelectorFromSet(labels.Set{autogenSourceLabel: pol.GetName()})

	vaps, err := c.vapLister.List(selector)
	if err != nil {
		return fmt.Errorf("failed to list autogen validatingadmissionpolicies for policy %s: %w", pol.GetName(), err)
	}
	for _, vap := range vaps {
		if _, active := activeNames[vap.Name]; active {
			continue
		}
		if err := c.client.AdmissionregistrationV1().ValidatingAdmissionPolicies().Delete(ctx, vap.Name, metav1.DeleteOptions{}); err != nil && !apierrors.IsNotFound(err) {
			return fmt.Errorf("failed to delete stale autogen validatingadmissionpolicy %s: %w", vap.Name, err)
		}
		bindingName := constructBindingName(vap.Name)
		if err := c.client.AdmissionregistrationV1().ValidatingAdmissionPolicyBindings().Delete(ctx, bindingName, metav1.DeleteOptions{}); err != nil && !apierrors.IsNotFound(err) {
			return fmt.Errorf("failed to delete stale autogen validatingadmissionpolicybinding %s: %w", bindingName, err)
		}
	}

	// Separately clean up any orphaned bindings whose parent VAP was already removed.
	vapbindings, err := c.vapbindingLister.List(selector)
	if err != nil {
		return fmt.Errorf("failed to list autogen validatingadmissionpolicybindings for policy %s: %w", pol.GetName(), err)
	}
	for _, binding := range vapbindings {
		vapName := binding.Spec.PolicyName
		if vapName == "" {
			vapName = strings.TrimSuffix(binding.Name, "-binding")
		}
		if _, active := activeNames[vapName]; active {
			continue
		}
		if err := c.client.AdmissionregistrationV1().ValidatingAdmissionPolicyBindings().Delete(ctx, binding.Name, metav1.DeleteOptions{}); err != nil && !apierrors.IsNotFound(err) {
			return fmt.Errorf("failed to delete stale autogen validatingadmissionpolicybinding %s: %w", binding.Name, err)
		}
	}

	return nil
}
