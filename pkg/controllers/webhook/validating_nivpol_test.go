func TestBuildWebhookRulesFineGrainedNamespacedImagePolicyAutogen(t *testing.T) {
	policy := &policiesv1beta1.NamespacedImageValidatingPolicy{
		ObjectMeta: metav1.ObjectMeta{
			Name:      "verify-images",
			Namespace: "team-a",
		},
		Spec: policiesv1beta1.ImageValidatingPolicySpec{
			MatchConstraints: &admissionregistrationv1.MatchResources{
				ResourceRules: []admissionregistrationv1.NamedRuleWithOperations{{
					RuleWithOperations: admissionregistrationv1.RuleWithOperations{
						Operations: []admissionregistrationv1.OperationType{admissionregistrationv1.Create},
						Rule: admissionregistrationv1.Rule{
							APIGroups:   []string{""},
							APIVersions: []string{"v1"},
							Resources:   []string{"pods"},
						},
					},
				}},
			},
			MatchConditions: []admissionregistrationv1.MatchCondition{{
				Name:       "always",
				Expression: "true",
			}},
		},
	}
	cache := NewExpressionCache()
	cache.AddPolicyExpressions(policy.GetMatchConditions())

	webhooks := buildWebhookRules(
		config.NewDefaultConfiguration(false),
		"",
		config.NamespacedImageValidatingPolicyValidateWebhookName,
		"/nivpol/validate",
		0,
		nil,
		[]engineapi.GenericPolicy{engineapi.NewNamespacedImageValidatingPolicy(policy)},
		cache,
	)

	if !assert.Len(t, webhooks, 1) {
		return
	}
	var hasDeploymentRule bool
	for _, rule := range webhooks[0].Rules {
		if slices.Contains(rule.APIGroups, "apps") && slices.Contains(rule.Resources, "deployments") {
			hasDeploymentRule = true
			break
		}
	}
	assert.True(t, hasDeploymentRule, "expected an autogenerated Deployment webhook rule")
}

func TestBuildForJSONPoliciesValidationSortsAndDeduplicatesNamespacedImagePolicyRules(t *testing.T) {
	newNivpol := func(name string) *policiesv1beta1.NamespacedImageValidatingPolicy {
		return &policiesv1beta1.NamespacedImageValidatingPolicy{
			ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: "team-a"},
			Spec: policiesv1beta1.ImageValidatingPolicySpec{
				MatchConstraints: &admissionregistrationv1.MatchResources{
					ResourceRules: []admissionregistrationv1.NamedRuleWithOperations{
						{RuleWithOperations: admissionregistrationv1.RuleWithOperations{
							Rule: admissionregistrationv1.Rule{
								APIGroups: []string{""}, APIVersions: []string{"v1"}, Resources: []string{"pods", "configmaps"},
							},
							Operations: []admissionregistrationv1.OperationType{admissionregistrationv1.Update, admissionregistrationv1.Create},
						}},
						{RuleWithOperations: admissionregistrationv1.RuleWithOperations{
							Rule: admissionregistrationv1.Rule{
								APIGroups: []string{""}, APIVersions: []string{"v1"}, Resources: []string{"pods", "configmaps"},
							},
							Operations: []admissionregistrationv1.OperationType{admissionregistrationv1.Create, admissionregistrationv1.Update},
						}},
					},
				},
			},
		}
	}
	nivpolIndexer := cache.NewIndexer(cache.MetaNamespaceKeyFunc, cache.Indexers{})
	require.NoError(t, nivpolIndexer.Add(newNivpol("a")))
	leaseIndexer := cache.NewIndexer(cache.MetaNamespaceKeyFunc, cache.Indexers{})
	require.NoError(t, leaseIndexer.Add(&coordinationv1.Lease{
		ObjectMeta: metav1.ObjectMeta{
			Name:        "kyverno-health",
			Namespace:   config.KyvernoNamespace(),
			Annotations: map[string]string{AnnotationLastRequestTime: time.Now().Format(time.RFC3339)},
		},
	}))
	empty := cache.NewIndexer(cache.MetaNamespaceKeyFunc, cache.Indexers{})
	c := &controller{
		vpolLister:         policiesv1beta1listers.NewValidatingPolicyLister(empty),
		nvpolLister:        policiesv1beta1listers.NewNamespacedValidatingPolicyLister(empty),
		gpolLister:         policiesv1beta1listers.NewGeneratingPolicyLister(empty),
		ngpolLister:        policiesv1beta1listers.NewNamespacedGeneratingPolicyLister(empty),
		ivpolLister:        policiesv1beta1listers.NewImageValidatingPolicyLister(empty),
		nivpolLister:       policiesv1beta1listers.NewNamespacedImageValidatingPolicyLister(nivpolIndexer),
		leaseLister:        coordinationv1listers.NewLeaseLister(leaseIndexer),
		stateRecorder:      NewStateRecorder(nil),
		celExpressionCache: NewExpressionCache(),
	}

	result := &admissionregistrationv1.ValidatingWebhookConfiguration{}
	require.NoError(t, c.buildForJSONPoliciesValidation(config.NewDefaultConfiguration(false), nil, result))

	var rules []admissionregistrationv1.RuleWithOperations
	for _, w := range result.Webhooks {
		if w.ClientConfig.Service != nil && w.ClientConfig.Service.Path != nil &&
			strings.HasPrefix(*w.ClientConfig.Service.Path, "/nivpol/validate") {
			rules = append(rules, w.Rules...)
		}
	}
	require.NotEmpty(t, rules, "nivpol validate webhook should be generated")
	require.Equal(t, sortedRules(deDuplicatedRules(rules)), rules,
		"nivpol webhook rules must be deduplicated and sorted like every other policy kind")
	require.Len(t, rules, 1, "the two identical rules must be collapsed into one")
}
