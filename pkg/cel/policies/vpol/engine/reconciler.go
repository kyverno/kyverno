package engine

import (
	"context"
	"sync"

	policiesv1beta1 "github.com/kyverno/api/api/policies.kyverno.io/v1beta1"
	"github.com/kyverno/kyverno/pkg/cel/engine"
	celpolicies "github.com/kyverno/kyverno/pkg/cel/policies"
	"github.com/kyverno/kyverno/pkg/cel/policies/vpol/autogen"
	"github.com/kyverno/kyverno/pkg/cel/policies/vpol/compiler"
	"github.com/kyverno/kyverno/pkg/logging"
	"k8s.io/apimachinery/pkg/api/errors"
	"k8s.io/apimachinery/pkg/util/sets"
	ctrl "sigs.k8s.io/controller-runtime"
	"sigs.k8s.io/controller-runtime/pkg/client"
)

type reconciler struct {
	client   client.Client
	compiler compiler.Compiler
	// reconcileLock serializes whole Reconcile calls. controller-runtime never reconciles the same
	// key concurrently, but WarmUp calls Reconcile outside the workqueue: without this lock a
	// WarmUp reconcile still compiling an older version of a policy could overwrite the newer
	// result written by a concurrent workqueue reconcile.
	reconcileLock sync.Mutex
	lock          *sync.RWMutex
	policies      map[string][]Policy
	polexLister   engine.PolicyExceptionLister
	polexEnabled  bool
}

func newReconciler(
	compiler compiler.Compiler,
	client client.Client,
	polexLister engine.PolicyExceptionLister,
	polexEnabled bool,
) *reconciler {
	return &reconciler{
		client:       client,
		compiler:     compiler,
		lock:         &sync.RWMutex{},
		policies:     map[string][]Policy{},
		polexLister:  polexLister,
		polexEnabled: polexEnabled,
	}
}

func (r *reconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	r.reconcileLock.Lock()
	defer r.reconcileLock.Unlock()
	var policy policiesv1beta1.ValidatingPolicyLike
	if req.NamespacedName.Namespace == "" {
		var vp policiesv1beta1.ValidatingPolicy
		err := r.client.Get(ctx, req.NamespacedName, &vp)
		if err != nil {
			if errors.IsNotFound(err) {
				r.lock.Lock()
				defer r.lock.Unlock()
				delete(r.policies, req.NamespacedName.String())
				return ctrl.Result{}, nil
			}
			return ctrl.Result{}, err
		}
		policy = &vp
	} else {
		var nvp policiesv1beta1.NamespacedValidatingPolicy
		err := r.client.Get(ctx, req.NamespacedName, &nvp)
		if err != nil {
			if errors.IsNotFound(err) {
				r.lock.Lock()
				defer r.lock.Unlock()
				delete(r.policies, req.NamespacedName.String())
				return ctrl.Result{}, nil
			}
			return ctrl.Result{}, err
		}
		policy = &nvp
	}
	if policy.GetStatus().Generated {
		r.lock.Lock()
		defer r.lock.Unlock()
		delete(r.policies, req.NamespacedName.String())
		return ctrl.Result{}, nil
	}
	if !celpolicies.IsKyvernoEvaluationMode(policy.GetValidatingPolicySpec().EvaluationMode()) {
		r.lock.Lock()
		defer r.lock.Unlock()
		delete(r.policies, req.NamespacedName.String())
		return ctrl.Result{}, nil
	}
	// get exceptions that match the policy
	var exceptions []*policiesv1beta1.PolicyException
	var err error
	if r.polexEnabled {
		exceptions, err = engine.ListExceptions(r.polexLister, policy.GetKind(), policy.GetName())
		if err != nil {
			return ctrl.Result{}, err
		}
	}
	compiled, errs := r.compiler.Compile(policy, exceptions)
	if len(errs) > 0 {
		logging.V(4).Info("failed to compile policy", "policy", policy.GetName(), "errors", errs)
		return ctrl.Result{}, nil
	}
	spec := policy.GetValidatingPolicySpec()
	actions := sets.New(spec.ValidationActions()...)
	policies := []Policy{{
		Actions:        actions,
		Policy:         policy,
		CompiledPolicy: compiled,
	}}
	generated, err := autogen.Autogen(policy)
	if err != nil {
		return ctrl.Result{}, err
	}
	for config, generatedPolicy := range generated {
		autogenPolicy := policy.DeepCopyObject().(policiesv1beta1.ValidatingPolicyLike)
		*autogenPolicy.GetValidatingPolicySpec() = *generatedPolicy.Spec

		rewrittenExceptions, err := autogen.RewriteExceptions(exceptions, config)
		if err != nil {
			return ctrl.Result{}, err
		}
		compiled, errs := r.compiler.Compile(autogenPolicy, rewrittenExceptions)
		if len(errs) > 0 {
			logging.V(4).Info("failed to compile autogenerated policy", "policy", policy.GetName(), "errors", errs)
			return ctrl.Result{}, nil
		}
		policies = append(policies, Policy{
			Actions:        actions,
			Policy:         autogenPolicy,
			CompiledPolicy: compiled,
			ExtractionMode: config == autogen.ExtractionReplacementsRef,
		})
	}
	r.lock.Lock()
	defer r.lock.Unlock()
	r.policies[req.NamespacedName.String()] = policies
	return ctrl.Result{}, nil
}

// WarmUp synchronously compiles every existing ValidatingPolicy and NamespacedValidatingPolicy so
// that Fetch returns them before the caller starts serving admission traffic. Policies that fail to
// reconcile are skipped, see engine.WarmUp.
func (r *reconciler) WarmUp(ctx context.Context) error {
	var vpols policiesv1beta1.ValidatingPolicyList
	if err := r.client.List(ctx, &vpols); err != nil {
		return err
	}
	var nvpols policiesv1beta1.NamespacedValidatingPolicyList
	if err := r.client.List(ctx, &nvpols); err != nil {
		return err
	}
	keys := make([]client.ObjectKey, 0, len(vpols.Items)+len(nvpols.Items))
	for i := range vpols.Items {
		keys = append(keys, client.ObjectKeyFromObject(&vpols.Items[i]))
	}
	for i := range nvpols.Items {
		keys = append(keys, client.ObjectKeyFromObject(&nvpols.Items[i]))
	}
	return engine.WarmUp(ctx, "ValidatingPolicy", r, keys)
}

func (r *reconciler) Fetch(ctx context.Context) ([]Policy, error) {
	r.lock.RLock()
	defer r.lock.RUnlock()
	policies := make([]Policy, 0, len(r.policies))
	for _, value := range r.policies {
		policies = append(policies, value...)
	}
	return policies, nil
}
