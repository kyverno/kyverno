type reconciler struct {
	client   client.Client
	compiler compiler.Compiler
	libCxt   libs.Context
	// reconcileLock serializes whole Reconcile calls. controller-runtime never reconciles the same
	// key concurrently, but WarmUp calls Reconcile outside the workqueue: without this lock a
	// WarmUp reconcile still compiling an older version of a policy could overwrite the newer
	// result written by a concurrent workqueue reconcile.
	reconcileLock sync.Mutex
	lock          *sync.RWMutex
	policies      map[string][]Policy
	polexLister   engine.PolicyExceptionLister
	polexEnabled  bool
}

func newReconciler(
	client client.Client,
	compiler compiler.Compiler,
	polexLister engine.PolicyExceptionLister,
	polexEnabled bool,
) *reconciler {
	return &reconciler{
		client:       client,
		compiler:     compiler,
		lock:         &sync.RWMutex{},
		policies:     map[string][]Policy{},
		polexLister:  polexLister,
		polexEnabled: polexEnabled,
	}
}

func (r *reconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	r.reconcileLock.Lock()
	defer r.reconcileLock.Unlock()
	var policy policiesv1beta1.MutatingPolicyLike
	var err error

	if req.NamespacedName.Namespace != "" {
		// Request has a namespace: this is always a NamespacedMutatingPolicy reconcile.
		// Do NOT try MutatingPolicy first — for cluster-scoped resources, controller-runtime
		// ignores the namespace in the request, so Get would silently find a same-named
		// cluster-scoped policy instead of returning NotFound.
		nmpol := &policiesv1beta1.NamespacedMutatingPolicy{}
		err = r.client.Get(ctx, req.NamespacedName, nmpol)
		if err == nil {
			policy = nmpol
		} else if errors.IsNotFound(err) {
			r.lock.Lock()
			delete(r.policies, req.NamespacedName.String())
			r.lock.Unlock()
			return ctrl.Result{}, nil
		} else {
			return ctrl.Result{}, err
		}
	} else {
		// No namespace: this is a MutatingPolicy (cluster-scoped) reconcile.
		mpol := &policiesv1beta1.MutatingPolicy{}
		err = r.client.Get(ctx, req.NamespacedName, mpol)
		if err == nil {
			policy = mpol
		} else if errors.IsNotFound(err) {
			r.lock.Lock()
			delete(r.policies, req.NamespacedName.String())
			r.lock.Unlock()
			return ctrl.Result{}, nil
		} else {
			return ctrl.Result{}, err
		}
	}

	// skip generated policies and policies owned by another controller, such as Kyverno Authz
	if policy.GetStatus().Generated || !celpolicies.IsKyvernoOwned(policy.GetSpec()) {
		r.lock.Lock()
		delete(r.policies, req.NamespacedName.String())
		r.lock.Unlock()
		return ctrl.Result{}, nil
	}

	var exceptions []*policiesv1beta1.PolicyException
	if r.polexEnabled {
		exceptions, err = engine.ListExceptions(r.polexLister, policy.GetKind(), policy.GetName())
		if err != nil {
			return ctrl.Result{}, err
		}
	}
	compiled, errs := r.compiler.Compile(policy, exceptions)
	if len(errs) > 0 {
		return ctrl.Result{}, errs.ToAggregate()
	}
	policies := []Policy{{
		Policy:         policy,
		CompiledPolicy: compiled,
	}}

	if policy.GetSpec().EvaluationMode() != policieskyvernoio.EvaluationModeJSON {
		generated, err := autogen.Autogen(policy)
		if err != nil {
			return ctrl.Result{}, err
		}
		for config, gen := range generated {
			// Create a copy of the policy with autogenerated spec
			autogenPolicy := policy.DeepCopyObject().(policiesv1beta1.MutatingPolicyLike)
			*autogenPolicy.GetSpec() = *gen.Spec

			compiled, errs := r.compiler.Compile(autogenPolicy, exceptions)
			if len(errs) > 0 {
				return ctrl.Result{}, errs.ToAggregate()
			}
			policies = append(policies, Policy{
				Policy:         autogenPolicy,
				CompiledPolicy: compiled,
				ExtractionMode: config == autogen.ExtractionReplacementsRef,
			})
		}
	}

	r.lock.Lock()
	r.policies[req.NamespacedName.String()] = policies
	r.lock.Unlock()
	return ctrl.Result{}, nil
}

// WarmUp synchronously compiles every existing MutatingPolicy and NamespacedMutatingPolicy so that
// Fetch returns them before the caller starts serving admission traffic. Policies that fail to
// reconcile are skipped, see engine.WarmUp.
func (r *reconciler) WarmUp(ctx context.Context) error {
	var mpols policiesv1beta1.MutatingPolicyList
	if err := r.client.List(ctx, &mpols); err != nil {
		return err
	}
	var nmpols policiesv1beta1.NamespacedMutatingPolicyList
	if err := r.client.List(ctx, &nmpols); err != nil {
		return err
	}
	keys := make([]client.ObjectKey, 0, len(mpols.Items)+len(nmpols.Items))
	for i := range mpols.Items {
		keys = append(keys, client.ObjectKeyFromObject(&mpols.Items[i]))
	}
	for i := range nmpols.Items {
		keys = append(keys, client.ObjectKeyFromObject(&nmpols.Items[i]))
	}
	return engine.WarmUp(ctx, "MutatingPolicy", r, keys)
}

func (r *reconciler) Fetch(ctx context.Context, mutateExisting bool) []Policy {
	r.lock.RLock()
	defer r.lock.RUnlock()
	var policies []Policy
	if !mutateExisting {
		for _, p := range r.policies {
			policies = append(policies, p...)
		}
		return policies
	}

	for _, p := range r.policies {
		for _, mpol := range p {
			if mpol.Policy.GetSpec().MutateExistingEnabled() {
				policies = append(policies, mpol)
			}
		}
	}
	return policies
}

func (r *reconciler) MatchesMutateExisting(ctx context.Context, attr admission.Attributes, request *admissionv1.AdmissionRequest, namespace *corev1.Namespace, requestMapFn func() (map[string]any, error)) []string {
	policies := r.Fetch(ctx, true)
	matchedPolicies := []string{}
	for _, mpol := range policies {
		// admission-disabled policies opt out of the admission plane entirely:
		// they are never triggered by admission requests, so exclude them from
		// admission-driven mutate-existing UR creation.
		if !mpol.Policy.GetSpec().AdmissionEnabled() {
			continue
		}
		if !Or(ClusteredPolicy(), NamespacedPolicy(attr.GetNamespace()))(mpol.Policy) {
			continue
		}

		matcher := matching.NewMatcher()
		matchConstraints := mpol.Policy.GetSpec().MatchConstraints
		if ok, err := matcher.Match(&matching.MatchCriteria{Constraints: matchConstraints}, attr, namespace); err != nil || !ok {
			continue
		}
		if mpol.Policy.GetSpec().MatchConditions != nil {
			if !mpol.CompiledPolicy.MatchesConditions(ctx, attr, request, namespace, requestMapFn, r.libCxt) {
				continue
			}
		}
		matchedPolicies = append(matchedPolicies, PolicyKey(mpol.Policy))
	}
	return matchedPolicies
}
