func (r *reconciler) Fetch(ctx context.Context) ([]Policy, error) {
	r.lock.RLock()
	defer r.lock.RUnlock()
	policies := make([]Policy, 0, len(r.policies))
	for _, value := range r.policies {
		policies = append(policies, value...)
	}
	return policies, nil
}
