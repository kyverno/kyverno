// fakeClient serves a fixed set of ImageValidatingPolicies by name so the reconciler can be driven
// without an API server.
type fakeClient struct {
	client.Client
	policies map[string]*policiesv1beta1.ImageValidatingPolicy
}

func (f *fakeClient) Get(_ context.Context, key client.ObjectKey, obj client.Object, _ ...client.GetOption) error {
	if p, ok := f.policies[key.Name]; ok {
		if o, ok := obj.(*policiesv1beta1.ImageValidatingPolicy); ok {
			*o = *p
			return nil
		}
	}
	return apierrors.NewNotFound(schema.GroupResource{}, key.Name)
}

// autogennablePolicy is a cluster ImageValidatingPolicy matching Pods on CREATE, which triggers
// autogen for pod controllers (Deployments, CronJobs, ...).
func autogennablePolicy(name string) *policiesv1beta1.ImageValidatingPolicy {
	return &policiesv1beta1.ImageValidatingPolicy{
		ObjectMeta: metav1.ObjectMeta{Name: name},
		Spec: policiesv1beta1.ImageValidatingPolicySpec{
			MatchConstraints: &admissionregistrationv1.MatchResources{
				ResourceRules: []admissionregistrationv1.NamedRuleWithOperations{{
					RuleWithOperations: admissionregistrationv1.RuleWithOperations{
						Operations: []admissionregistrationv1.OperationType{admissionregistrationv1.Create},
						Rule: admissionregistrationv1.Rule{
							APIGroups:   []string{""},
							APIVersions: []string{"v1"},
							Resources:   []string{"pods"},
						},
					},
				}},
			},
		},
	}
}

// targetsDeployments reports whether a compiled policy entry matches Deployments, i.e. it is an
// autogen pod-controller variant.
func targetsDeployments(p Policy) bool {
	mc := p.Policy.GetSpec().MatchConstraints
	if mc == nil {
		return false
	}
	for _, rule := range mc.ResourceRules {
		for _, res := range rule.Resources {
			if strings.Contains(res, "deployments") {
				return true
			}
		}
	}
	return false
}

// deploymentVariantsByPolicy counts, per policy name, how many entries in the fetched set target
// Deployments.
func deploymentVariantsByPolicy(policies []Policy) map[string]int {
	out := map[string]int{}
	for _, p := range policies {
		if targetsDeployments(p) {
			out[p.Policy.GetName()]++
		}
	}
	return out
}

// TestReconcile_TwoPolicies_DoNotClobberAutogenVariants is the regression test for issue #16729: two
// autogennable ImageValidatingPolicies must each keep their own autogenerated pod-controller variants.
// Before the fix, the reconciler stored every policy's variants under shared global keys ("/defaults",
// "/cronjobs"), so the second policy's variants overwrote the first's and its image verification was
// silently skipped for Deployments and other workload controllers.
func TestReconcile_TwoPolicies_DoNotClobberAutogenVariants(t *testing.T) {
	ctx := context.Background()
	alpha := autogennablePolicy("alpha")
	beta := autogennablePolicy("beta")

	rec := newReconciler(iveval.NewCompiler(nil),
		&fakeClient{policies: map[string]*policiesv1beta1.ImageValidatingPolicy{
			"alpha": alpha,
			"beta":  beta,
		}},
		nil, false,
	)

	_, err := rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: "alpha"}})
	require.NoError(t, err)
	_, err = rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: "beta"}})
	require.NoError(t, err)

	fetched, err := rec.Fetch(ctx)
	require.NoError(t, err)

	variants := deploymentVariantsByPolicy(fetched)
	assert.Equal(t, 1, variants["alpha"], "alpha must keep its own Deployment autogen variant")
	assert.Equal(t, 1, variants["beta"], "beta must keep its own Deployment autogen variant")
}

// autogennablePolicyWithJobSet is like autogennablePolicy but also autogens onto a custom workload
// CRD named by the explicit "<resource>.<version>.<group>" format, which does not need a live cluster
// to resolve.
func autogennablePolicyWithJobSet(name string) *policiesv1beta1.ImageValidatingPolicy {
	p := autogennablePolicy(name)
	p.Spec.AutogenConfiguration = &policiesv1beta1.ImageValidatingPolicyAutogenConfiguration{
		PodControllers: &policiesv1beta1.PodControllersGenerationConfiguration{
			Controllers: []string{"deployments", "jobsets.v1alpha2.jobset.x-k8s.io"},
		},
	}
	return p
}

// TestReconcile_ExtractionMode is the regression test for the gap that let the ivpol extraction
// wiring ship without actually working end to end: provider.go (used by NewProvider, the CLI/test
// path) set Policy.ExtractionMode correctly, but reconciler.go (used by the live cluster controller)
// had its own separate copy of the same loop that never set it, so the live admission path evaluated
// the custom-CRD target directly against the real object instead of extracting its pod template.
func TestReconcile_ExtractionMode(t *testing.T) {
	ctx := context.Background()
	rec := newReconciler(iveval.NewCompiler(nil),
		&fakeClient{policies: map[string]*policiesv1beta1.ImageValidatingPolicy{
			"alpha": autogennablePolicyWithJobSet("alpha"),
		}},
		nil, false,
	)

	_, err := rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: "alpha"}})
	require.NoError(t, err)

	fetched, err := rec.Fetch(ctx)
	require.NoError(t, err)
	require.Len(t, fetched, 3, "expected the base policy plus one autogen'd variant per ReplacementsRef group")

	var sawDeploymentVariant, sawJobSetVariant bool
	for _, p := range fetched {
		mc := p.Policy.GetSpec().MatchConstraints
		if mc == nil || len(mc.ResourceRules) == 0 {
			continue // the base, Pod-targeted policy
		}
		resources := mc.ResourceRules[0].Resources
		switch {
		case len(resources) > 0 && resources[0] == "deployments":
			sawDeploymentVariant = true
			assert.False(t, p.ExtractionMode, "the built-in deployments variant must not be extraction-mode")
		case len(resources) > 0 && resources[0] == "jobsets":
			sawJobSetVariant = true
			assert.True(t, p.ExtractionMode, "the custom-CRD jobsets variant must be extraction-mode")
		}
	}
	assert.True(t, sawDeploymentVariant, "expected a deployments autogen variant")
	assert.True(t, sawJobSetVariant, "expected a jobsets autogen variant")
}

// TestReconcile_DeleteRemovesAllVariants covers the leak side of the same bug: deleting a policy must
// remove its autogenerated variants too, not just the primary entry.
func TestReconcile_DeleteRemovesAllVariants(t *testing.T) {
	ctx := context.Background()
	fc := &fakeClient{policies: map[string]*policiesv1beta1.ImageValidatingPolicy{
		"alpha": autogennablePolicy("alpha"),
	}}
	rec := newReconciler(iveval.NewCompiler(nil), fc, nil, false)

	_, err := rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: "alpha"}})
	require.NoError(t, err)
	fetched, err := rec.Fetch(ctx)
	require.NoError(t, err)
	require.NotEmpty(t, fetched, "alpha should be present after reconcile")

	// Delete alpha (the fake client now returns NotFound for it).
	delete(fc.policies, "alpha")
	_, err = rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: "alpha"}})
	require.NoError(t, err)

	fetched, err = rec.Fetch(ctx)
	require.NoError(t, err)
	assert.Empty(t, fetched, "deleting a policy must remove its primary entry and all autogen variants")
}

func TestReconcile_Fetch_DeterministicOrdering(t *testing.T) {
	ctx := context.Background()
	policies := map[string]*policiesv1beta1.ImageValidatingPolicy{
		"alpha":   autogennablePolicy("alpha"),
		"beta":    autogennablePolicy("beta"),
		"gamma":   autogennablePolicy("gamma"),
		"delta":   autogennablePolicy("delta"),
		"epsilon": autogennablePolicy("epsilon"),
	}

	fc := &fakeClient{policies: policies}
	rec := newReconciler(iveval.NewCompiler(nil), fc, nil, false)

	for name := range policies {
		_, err := rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: name}})
		require.NoError(t, err)
	}

	firstFetched, err := rec.Fetch(ctx)
	require.NoError(t, err)
	firstOrder := variantOrder(firstFetched)
	var policyOrder []string
	for _, p := range firstFetched {
		name := p.Policy.GetName()
		if len(policyOrder) == 0 || policyOrder[len(policyOrder)-1] != name {
			policyOrder = append(policyOrder, name)
		}
	}
	assert.Equal(t, []string{"alpha", "beta", "delta", "epsilon", "gamma"}, policyOrder)

	for i := 0; i < 50; i++ {
		fetched, err := rec.Fetch(ctx)
		require.NoError(t, err)
		currentOrder := variantOrder(fetched)
		assert.Equal(t, firstOrder, currentOrder, "reconciler.Fetch must return deterministic order at iteration %d", i)
	}
}

func TestReconcile_AutogenVariantDeterministicOrdering(t *testing.T) {
	ctx := context.Background()
	fc := &fakeClient{policies: map[string]*policiesv1beta1.ImageValidatingPolicy{
		"alpha": autogennablePolicy("alpha"),
	}}
	var baseline []string
	for i := 0; i < 50; i++ {
		rec := newReconciler(iveval.NewCompiler(nil), fc, nil, false)
		_, err := rec.Reconcile(ctx, reconcile.Request{NamespacedName: types.NamespacedName{Name: "alpha"}})
		require.NoError(t, err)
		fetched, err := rec.Fetch(ctx)
		require.NoError(t, err)

		order := variantOrder(fetched)
		if i == 0 {
			baseline = order
			require.Greater(t, len(baseline), 1, "expected autogennable policy to generate variants")
		} else {
			assert.Equal(t, baseline, order, "reconcile autogen variants order must be deterministic at iteration %d", i)
		}
	}
}

func variantOrder(policies []Policy) []string {
	var order []string
	for _, p := range policies {
		ruleNames := ""
		if mc := p.Policy.GetSpec().MatchConstraints; mc != nil && len(mc.ResourceRules) > 0 {
			ruleNames = strings.Join(mc.ResourceRules[0].Resources, ",")
		}
		order = append(order, fmt.Sprintf("%s:%s:%t", p.Policy.GetName(), ruleNames, p.ExtractionMode))
	}
	return order
}

// fixedExceptionLister serves a fixed set of PolicyExceptions.
type fixedExceptionLister []*policiesv1beta1.PolicyException

func (l fixedExceptionLister) List(labels.Selector) ([]*policiesv1beta1.PolicyException, error) {
	return l, nil
}

// The reconciler compiles live exceptions into the cached policy and its autogen variants, so it
// must requeue itself for the earliest expiresAt and stop attaching the exception once it lapses.
func TestReconcile_ExpiringExceptionRequeuesAndLapses(t *testing.T) {
	ctx := context.Background()
	policy := autogennablePolicy("require-signed")
	fc := &fakeClient{policies: map[string]*policiesv1beta1.ImageValidatingPolicy{policy.Name: policy}}
	req := reconcile.Request{NamespacedName: types.NamespacedName{Name: policy.Name}}
	inAnHour := metav1.NewTime(time.Now().Add(time.Hour))
	exception := &policiesv1beta1.PolicyException{
		ObjectMeta: metav1.ObjectMeta{Name: "exempt"},
		Spec: policiesv1beta1.PolicyExceptionSpec{
			ExpiresAt:  &inAnHour,
			PolicyRefs: []policiesv1beta1.PolicyRef{{Name: policy.Name, Kind: policy.GetKind()}},
		},
	}
	lister := fixedExceptionLister{exception}
	rec := newReconciler(iveval.NewCompiler(nil), fc, lister, true)

	res, err := rec.Reconcile(ctx, req)
	require.NoError(t, err)
	assert.Greater(t, res.RequeueAfter, 59*time.Minute)
	assert.LessOrEqual(t, res.RequeueAfter, time.Hour)
	fetched, err := rec.Fetch(ctx)
	require.NoError(t, err)
	require.NotEmpty(t, fetched)
	for _, p := range fetched {
		assert.Len(t, p.Exceptions, 1, "a live exception must be attached to the policy and every autogen variant")
	}

	lapsed := metav1.NewTime(time.Now().Add(-time.Second))
	exception.Spec.ExpiresAt = &lapsed
	res, err = rec.Reconcile(ctx, req)
	require.NoError(t, err)
	assert.Zero(t, res.RequeueAfter)
	fetched, err = rec.Fetch(ctx)
	require.NoError(t, err)
	for _, p := range fetched {
		assert.Empty(t, p.Exceptions, "an expired exception must no longer be attached")
	}
}
